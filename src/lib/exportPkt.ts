import type { NetworkTopology } from '@/types/network';
import { prefixToMask } from './ip';

interface PktExportOptions {
  projectName: string;
  topology: NetworkTopology;
  layout: Record<string, { x: number; y: number }>;
}

export function exportPacketTracerFile({ projectName, topology, layout }: PktExportOptions): void {
  const devices = Object.values(topology.devices);
  const links = Object.values(topology.links);

  // Generate Cisco Packet Tracer XML interchange format
  const xmlDevices = devices.map((dev) => {
    const pos = layout[dev.id] || { x: 100, y: 100 };
    
    // Map TopoSphere types to standard Cisco Packet Tracer models
    let cptType = 'router';
    let cptModel = 'Cisco 4331';
    if (dev.type === 'switch') {
      cptType = 'switch';
      cptModel = '2960-24TT';
    } else if (dev.type === 'switch-l3') {
      cptType = 'switch';
      cptModel = '3650-24TS';
    } else if (dev.type === 'pc') {
      cptType = 'pc';
      cptModel = 'PC-PT';
    } else if (dev.type === 'server') {
      cptType = 'server';
      cptModel = 'Server-PT';
    } else if (dev.type === 'laptop') {
      cptType = 'laptop';
      cptModel = 'Laptop-PT';
    }

    const interfacesXml = Object.values(dev.interfaces).map((iface) => {
      const ip = iface.ipv4?.address || '';
      const mask = iface.ipv4 ? prefixToMask(iface.ipv4.prefixLength) : '';
      const gw = iface.ipv4?.gateway || '';
      return `      <port name="${iface.name}" shortName="${iface.shortName}" mac="${iface.mac}" ip="${ip}" mask="${mask}" gateway="${gw}" adminState="${iface.adminState}" vlanMode="${iface.vlanMode}" vlan="${iface.accessVlan}" />`;
    }).join('\n');

    // IOS startup-config script
    const configLines: string[] = [
      `! Cisco Packet Tracer Startup Configuration`,
      `! Generated by TopoSphere Network Simulator`,
      `version 15.6`,
      `hostname ${dev.hostname}`,
      `!`,
    ];

    Object.values(dev.vlans).forEach((v) => {
      if (v.id !== 1) configLines.push(`vlan ${v.id}`, ` name ${v.name}`, `!`);
    });

    Object.values(dev.interfaces).forEach((i) => {
      configLines.push(`interface ${i.name}`);
      if (i.ipv4) configLines.push(` ip address ${i.ipv4.address} ${prefixToMask(i.ipv4.prefixLength)}`);
      if (i.vlanMode === 'trunk') configLines.push(` switchport mode trunk`);
      else if (i.vlanMode === 'access' && i.accessVlan !== 1) configLines.push(` switchport access vlan ${i.accessVlan}`);
      if (i.adminState === 'up') configLines.push(` no shutdown`);
      else configLines.push(` shutdown`);
      configLines.push(`!`);
    });

    dev.staticRoutes.forEach((sr) => {
      configLines.push(`ip route ${sr.network} ${prefixToMask(sr.prefixLength)} ${sr.nextHop}`);
    });
    configLines.push(`end`);

    return `    <device id="${dev.id}" name="${dev.hostname}" type="${cptType}" model="${cptModel}" x="${Math.round(pos.x)}" y="${Math.round(pos.y)}">
      <interfaces>
${interfacesXml}
      </interfaces>
      <ios-config>
<![CDATA[
${configLines.join('\n')}
]]>
      </ios-config>
    </device>`;
  }).join('\n');

  const xmlLinks = links.map((l) => {
    const srcDev = topology.devices[l.sourceDeviceId];
    const tgtDev = topology.devices[l.targetDeviceId];
    const srcIface = srcDev?.interfaces[l.sourceInterfaceId]?.name || l.sourceInterfaceId;
    const tgtIface = tgtDev?.interfaces[l.targetInterfaceId]?.name || l.targetInterfaceId;

    return `    <link id="${l.id}" type="copper-straight-through">
      <endpoint device="${l.sourceDeviceId}" deviceName="${srcDev?.hostname}" port="${srcIface}" />
      <endpoint device="${l.targetDeviceId}" deviceName="${tgtDev?.hostname}" port="${tgtIface}" />
    </link>`;
  }).join('\n');

  const pktContent = `<?xml version="1.0" encoding="UTF-8"?>
<!-- TopoSphere to Cisco Packet Tracer Interchange Specification v5.0 -->
<packet-tracer-project name="${projectName}" version="8.2" generator="TopoSphere">
  <meta>
    <generator>TopoSphere Web Simulator</generator>
    <created>${new Date().toISOString()}</created>
    <deviceCount>${devices.length}</deviceCount>
    <linkCount>${links.length}</linkCount>
  </meta>
  <devices>
${xmlDevices}
  </devices>
  <links>
${xmlLinks}
  </links>
</packet-tracer-project>`;

  const blob = new Blob([pktContent], { type: 'application/octet-stream' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${projectName.toLowerCase().replace(/\s+/g, '-')}.pkt`;
  a.click();
  URL.revokeObjectURL(url);
}
